export function parseVsPairSlug(pairSlug: string): { product1?: DirectoryProduct; product2?: DirectoryProduct } {
  const parts = pairSlug.split('-vs-');
  if (parts.length !== 2) return {};
  return {
    product1: getDirectoryProductByIdOrSlug(parts[0]),
    product2: getDirectoryProductByIdOrSlug(parts[1]),
  };
}

