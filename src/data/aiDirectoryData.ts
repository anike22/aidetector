export function getDirectoryProductByIdOrSlug(idOrSlug: string): DirectoryProduct | undefined {
  const normalized = idOrSlug.toLowerCase().trim();
  return AI_DIRECTORY_PRODUCTS.find(
    p => p.id.toLowerCase() === normalized || p.slug.toLowerCase() === normalized
  );
}

